"""Strict actual V8 parent proposal and V3 preparation value component.

The catalog must first prove every ancestor input and HISTORY_FIELDS value.
This component independently projects SQL/frozen-byte frames at the actual
check and preparation boundaries. It does not certify caller-supplied saved
paths, admit an ancestor codec, construct a runtime owner, or close a catalog.
"""
from copy import deepcopy
from types import SimpleNamespace

from .store import digest
from .work_transitions import plan_ref
from .work_proposals import parse
from .work_coordinator_handoff_records import fields, reference
from .work_coordinator_handoff_adjustment_records import finite, SOURCE_FIELDS
from .work_coordinator_handoff_context import WorkCoordinatorHandoffContext
from .work_coordinator_handoff_mixed_runtime import WorkCoordinatorHandoffMixedRuntime
from .work_coordinator_handoff_post_round_candidates import ref
from .work_coordinator_handoff_post_round_v2_preview import rebuild_preview
from .work_coordinator_handoff_post_round_v2_run_contracts import PROTOCOL
from .work_coordinator_handoff_post_round_v3_candidates import (
    WorkCoordinatorHandoffPostRoundV3Candidates, CHECKPOINT, CANDIDATE,
    HISTORY_FIELDS, KINDS, EVENTS, validate_row)
from .work_coordinator_handoff_historical_assets import _json, _uuid


def event_value(event):
    """Original saved/path codecs have three fields; temporal proofs have four."""
    return {k: event[k] for k in ('seq', 'kind', 'payload_digest')}


class HistoricalParent:
    def __init__(self, sources, timeline, ledger, proven_inputs):
        if (timeline.sources is not sources or ledger.sources is not sources or
                not sources.db.in_transaction):
            raise ValueError('历史父来源须属于本次真实连接及事务。')
        self.sources, self.timeline, self.ledger = sources, timeline, ledger
        self.db = sources.db
        # Same contract as HistoricalAB: these values must be generated by the
        # enclosing independent ancestor replay, never copied from run.input.
        self.inputs = deepcopy(proven_inputs)
        self.s = SimpleNamespace(collaboration=sources,
            work_drivers=SimpleNamespace(reference=lambda v: {k: v[k] for k in ('id', 'generation', 'revision')}),
            work_units=SimpleNamespace(auth_ref=lambda v: {k: v[k] for k in ('id', 'revision')}))

    def frames_at(self, plan, boundary):
        if (type(boundary) is not int or
                self.db.execute('SELECT 1 FROM events WHERE seq=?', (boundary,)).fetchone() is None or
                plan not in self.timeline.plans):
            raise ValueError('历史父方案须属于本次准确原祖先。')
        ancestors = self.timeline.plans[:self.timeline.plans.index(plan) + 1]
        known = []
        for run in self.sources.all(self.db, 'work_unit_run'):
            if run.get('item_id') != plan['item_id']:
                continue
            actual, _, _, source_plan, _, reserved = self.sources.run(run['id'])
            if reserved['seq'] >= boundary:
                continue
            if source_plan not in ancestors:
                raise ValueError('父历史边界含不属于原祖先的运行。')
            frozen = self.inputs.get(run['id'])
            if actual != run or frozen is None or run['input'] != frozen:
                raise ValueError('父历史不能以run自身输入替代独立祖先输入。')
            known.append((reserved['seq'], run, frozen))
        known.sort(key=lambda v: v[0])
        if [r['ordinal_total'] for _, r, _ in known] != list(range(1, len(known) + 1)):
            raise ValueError('父历史准确祖先运行序号不连续。')
        return [self.sources.frame_at(run, boundary, frozen['dependencies']) for _, run, frozen in known]

    def boundary(self, plan, history, boundary):
        """Check dynamic fields; caller still owns ALL saved/static fields."""
        frames = self.frames_at(plan, boundary)
        driver = self.timeline.driver_before(plan, boundary)
        business = self.timeline.business_before(boundary)
        actual_usage = self.sources.usage([f['run'] for f in frames], boundary)
        usage = deepcopy(history['usage'])
        usage.pop('elapsed_observed_seconds', None)
        actual_usage.pop('elapsed_observed_seconds', None)
        eligible = WorkCoordinatorHandoffMixedRuntime._eligible(None, plan, frames)
        if (history['frames'] != frames or history['current_frames'] != eligible or
                history['frontier'] != [WorkCoordinatorHandoffContext.frontier_entry(f) for f in frames] or
                history['driver'] != driver or history['task'] != {'id': plan['item_id'], 'revision': driver['item_revision']} or
                business['revision'] != driver['item_revision'] or usage != actual_usage):
            raise ValueError('父历史frames、原责任、业务版本或范围累计不等于真实边界。')
        auth = WorkCoordinatorHandoffContext(self.s)._auth(self.db, plan,
            {k: history['authorization'][k] for k in ('id', 'revision')})
        if auth != history['authorization'] or auth['driver_generation'] != driver['generation']:
            raise ValueError('父历史原授权不等于准确不可变转移版本。')
        self.sources.assets.baseline(history['material_observation'])
        return frames

    def v8_proposal(self, plan, history, identity):
        return self.adjustment_proposal(plan, history, identity, stage='POST_V2')

    def adjustment_proposal(self, plan, history, identity, *, stage):
        """Exact successful V6/V7/V8 adjustment, previous and full receipt."""
        if stage == 'POST_V2':
            protocol, preview_codec = PROTOCOL, rebuild_preview
        elif stage == 'POST_V1':
            from .work_coordinator_handoff_post_round_successor_contracts import PROTOCOL as protocol
            from .work_coordinator_handoff_post_round_successor_preview import rebuild_preview as preview_codec
        elif stage == 'POST_ROUND':
            from .work_coordinator_handoff_post_round_contracts import PROTOCOL as protocol
            from .work_coordinator_handoff_post_round_preview import rebuild_preview as preview_codec
        else:
            raise ValueError('POST父提案须使用原V6、V7或V8codec。')
        reference(identity)
        proposal = self.sources.get(self.db, 'work_proposal', identity['id'])
        fields(proposal, {'id', 'version', 'snapshot', 'item_id', 'created', 'command_id'})
        finite(proposal['created']); _uuid(proposal['command_id'])
        if ref(proposal) != identity or proposal['item_id'] != plan['item_id']:
            raise ValueError('父提案须保持准确原完整身份。')
        b = proposal['snapshot']; source_id = b['source']['run_id']
        run, _, _, actual_plan, _, _ = self.sources.run(source_id)
        if actual_plan != plan:
            raise ValueError('父提案源运行须属于准确原父方案。')
        event = self.sources._event(self.db, 'coordinator_proposal_checked', proposal,
            task=run['task_id'], attempt=run['attempt_id'])
        frames = self.boundary(plan, history, event['seq'])
        coordinators = [f for f in frames if f['run']['input']['unit']['role'] == 'coordinate']
        if not coordinators or coordinators[-1]['run'] != run:
            raise ValueError('父提案须消费当时最新真实协调运行。')
        frame = coordinators[-1]; full = frame['source_evidence']; frozen = self.inputs[source_id]
        context = frozen['handoff_coordination_context']
        driver, auth = history['driver'], history['authorization']
        if (context['protocol'] != protocol or driver['state'] != 'RESERVED' or
                driver['generation'] != run['generation'] or not full['exact_identity'] or
                not full['result_available'] or full['state'] != 'COMPLETED' or full['blockers']):
            raise ValueError('父提案缺少原V8、准确责任或已知成功退出。')
        decision = parse(full['answer'])
        if decision['action'] != 'adjust_dependencies':
            raise ValueError('V3保存父须为原V8严格依赖调整决定。')
        preview = preview_codec(plan, history, run, decision, observed_at=proposal['created'])
        frontier = digest([{'run_id': f['run']['id'], 'evidence': f['evidence']['version']} for f in frames])
        expected = {'item_revision': history['task']['revision'],
            'driver': self.s.work_drivers.reference(driver), 'plan': plan_ref(plan),
            'authorization': self.s.work_units.auth_ref(auth), 'frontier': frontier,
            'state': 'POST_ROUND_ADJUSTMENT_PREVIEW', 'decision': decision, 'target': None, 'problems': [],
            'source': {k: full[k] for k in SOURCE_FIELDS}, 'answer_digest': digest(full['answer']),
            'answer': full['answer'], 'handoff_context': frozen['coordination_context']['handoff_context'],
            'adjustment': preview}
        if b != expected or proposal['version'] != digest(expected):
            raise ValueError('父提案完整snapshot不等于原回复及原时刻预览。')
        previous = []
        for raw in self.db.execute("SELECT * FROM events WHERE kind='coordinator_proposal_checked' AND seq<? ORDER BY seq", (event['seq'],)):
            value = _json(raw['payload'])
            if value.get('item_id') == plan['item_id']:
                if self.sources.get(self.db, 'work_proposal', value['id']) != value:
                    raise ValueError('父提案previous须为真实准确检查记录。')
                previous.append(value)
        request = {'id': plan['item_id'], 'revision': history['task']['revision'],
            'current_driver': self.s.work_drivers.reference(driver), 'plan': plan_ref(plan),
            'authorization': self.s.work_units.auth_ref(auth), 'frontier': frontier,
            'run_id': run['id'], 'result_version': full['version'],
            'proposal': ref(previous[-1]) if previous else None}
        owner = 'proposal:' + proposal['id']
        self.ledger.row('work_proposal', proposal, owner)
        self.ledger.event_at(event['seq'], event['kind'], proposal, owner, task=run['task_id'], attempt=run['attempt_id'])
        self.ledger.command(proposal['command_id'], 'work-item.proposal-check', request,
            {'proposal': proposal, 'no_dispatch': True}, owner,
            not_before=max(proposal['created'], event['created']))
        return {'plan': deepcopy(plan), 'proposal': proposal, 'history': deepcopy(history),
            'preview': preview, 'source_check_event': event_value(event)}

    def preparation(self, checkpoint, candidate, facts):
        """Compare original seven fields and every original HISTORY_FIELDS value.

        facts.history must already come from the independent ancestor owner.
        This method deliberately does not call SavedComponent._saved or grant
        permission to an unproved saved path/capability/history argument.
        """
        validate_row(checkpoint, CHECKPOINT); validate_row(candidate, CANDIDATE)
        h, plan, proposal = facts['history'], facts['plan'], facts['proposal']
        if not HISTORY_FIELDS <= h.keys():
            raise ValueError('原V3准备缺少独立重建的完整历史字段。')
        cp = checkpoint['snapshot']; cutoff = cp['cutoff']
        self.boundary(plan, h, cutoff + 1)
        request = {'id': plan['item_id'], 'revision': h['task']['revision'],
            'current_driver': self.s.work_drivers.reference(h['driver']), 'plan': plan_ref(plan),
            'authorization': self.s.work_units.auth_ref(h['authorization']),
            'frontier': digest([{'run_id': f['run']['id'], 'evidence': f['evidence']['version']} for f in h['frames']]),
            'proposal': ref(proposal)}
        # Candidates has no runtime/current owner; these are pure value methods.
        values = WorkCoordinatorHandoffPostRoundV3Candidates(self.s)
        if (cp != values._checkpoint(facts, request, cutoff) or
                candidate['snapshot'] != values._candidate(facts, checkpoint, candidate['snapshot']['child_seed']) or
                checkpoint['command_id'] != candidate['command_id']):
            raise ValueError('原V3准备完整值或原七字段不等于独立历史事实。')
        owner = 'saved:' + candidate['id']
        events = []
        for protocol, row in ((CHECKPOINT, checkpoint), (CANDIDATE, candidate)):
            self.ledger.row(KINDS[protocol], row, owner)
            events.append(self.ledger.event(EVENTS[protocol], row, owner))
        if (events[0]['seq'] != cutoff + 1 or events[1]['seq'] != cutoff + 2 or
                facts['source_check_event']['seq'] > cutoff):
            raise ValueError('原V3准备事件与原cutoff不连续。')
        return deepcopy(facts)
