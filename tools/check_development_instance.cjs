/* One real registered development instance; local UI only, no model dispatch. */
const {chromium}=require('C:/Users/naoki/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('fs'),path=require('path'),assert=require('assert/strict'),{execFileSync}=require('child_process');
const root=path.resolve(__dirname,'..');
const config=execFileSync('git',['-C',root,'config','--local','--get','workdesk.instanceConfig'],{encoding:'utf8'}).trim();
const profile=JSON.parse(fs.readFileSync(config,'utf8'));
assert.equal(profile.channel,'development');assert.equal(path.resolve(profile.program_root),root);
const output=path.join(profile.development_root,'artifacts','stage0-instance-ui');fs.mkdirSync(output,{recursive:true});
const state=JSON.parse(fs.readFileSync(path.join(profile.user_root,'runtime/ui','instance-'+profile.instance_id+'.json'),'utf8'));
const origin='http://127.0.0.1:'+state.port;
let browser,page;
(async()=>{
  const health=await (await fetch(origin+'/health')).json();
  assert.equal(health.instance_id,profile.instance_id);assert.equal(health.instance,state.instance);
  browser=await chromium.launch({headless:true,channel:'msedge'});
  page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[],commands=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/api/v1/command'))commands.push(r.postDataJSON().kind);});
  await page.route('https://**/*',r=>r.abort());
  await page.goto(origin+'/s/'+state.token+'/#work');
  await page.getByRole('textbox',{name:'工作目标',exact:true}).waitFor();
  await page.getByRole('button',{name:'开发 · 实例详情',exact:true}).waitFor();
  const identity=await page.evaluate(async()=>await (await fetch('api/v1/instance')).json());
  for(const field of ['instance_id','program_root','user_root','data_root'])assert.equal(identity[field],profile[field]);
  assert.equal(await page.title(),'Workdesk · 开发');
  assert.match(await page.locator('.wk-project-chip').innerText(),/repo/);
  await page.getByRole('button',{name:'开发 · 实例详情',exact:true}).click();
  await page.getByRole('dialog',{name:'Workdesk · 开发实例',exact:true}).waitFor();
  assert((await page.locator('#wd-instance-dialog').innerText()).includes(profile.data_root));
  await page.screenshot({path:path.join(output,'instance-details.png')});
  await page.getByRole('button',{name:'关闭实例详情',exact:true}).click();
  await page.screenshot({path:path.join(output,'development-work.png')});
  await page.setViewportSize({width:560,height:820});
  const bar=page.locator('[data-instance-channel="development"]');await bar.waitFor();
  const box=await bar.boundingBox();assert(box&&box.x>=0&&box.x+box.width<=561);
  await page.screenshot({path:path.join(output,'development-narrow.png')});
  assert.deepEqual(errors,[]);assert(!commands.some(k=>/^(independent.send|chat.api-send|task.start)$/.test(k)));
  const native=JSON.parse(fs.readFileSync(path.join(profile.user_root,'runtime/desktop/native-status.json'),'utf8'));
  assert.equal(native.title,'Workdesk · 开发');
  const result={checks:['real development identity and paths','registered development project selected','identity dialog and narrow layout','native desktop title'],identity,errors,real_model_requests:0};
  fs.writeFileSync(path.join(output,'check.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify({checks:result.checks,errors,real_model_requests:0}));
})().catch(async error=>{console.error(error.message);if(page)await page.screenshot({path:path.join(output,'failure.png')}).catch(()=>{});process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();});
